-- ============================================================
-- SPMS - School Parking Management System
-- Database schema for PostgreSQL
-- File: database_schema.sql
-- Run this script after creating/selecting the database spms_db.
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    full_name       VARCHAR(120) NOT NULL,
    role            VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'GUARD', 'STUDENT')),
    student_code    VARCHAR(30) UNIQUE,
    phone           VARCHAR(20),
    email           VARCHAR(120),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS parking_lots (
    parking_lot_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_name        VARCHAR(100) NOT NULL UNIQUE,
    location        VARCHAR(255),
    capacity        INTEGER NOT NULL CHECK (capacity >= 0),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS vehicles (
    vehicle_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number    VARCHAR(20) NOT NULL UNIQUE,
    vehicle_type    VARCHAR(30) NOT NULL CHECK (vehicle_type IN ('MOTORBIKE', 'E_BIKE', 'BICYCLE', 'CAR', 'OTHER')),
    brand           VARCHAR(80),
    color           VARCHAR(40),
    user_id         BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cards (
    card_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_uid        VARCHAR(100) NOT NULL UNIQUE,
    card_type       VARCHAR(20) NOT NULL CHECK (card_type IN ('MONTHLY', 'CASUAL')),
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED')),
    user_id         BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    issued_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at      TIMESTAMPTZ,
    note            TEXT,
    CHECK (expires_at IS NULL OR expires_at > issued_at)
);

CREATE TABLE IF NOT EXISTS monthly_card_registrations (
    registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    vehicle_id      BIGINT NOT NULL REFERENCES vehicles(vehicle_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    card_id         BIGINT REFERENCES cards(card_id) ON UPDATE CASCADE ON DELETE SET NULL,
    submitted_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    start_date      DATE,
    end_date        DATE,
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'EXPIRED')),
    reviewed_by     BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    reviewed_at     TIMESTAMPTZ,
    document_path   TEXT,
    note            TEXT,
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS tariff_rules (
    tariff_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tariff_name     VARCHAR(100) NOT NULL,
    vehicle_type    VARCHAR(30) CHECK (vehicle_type IN ('MOTORBIKE', 'E_BIKE', 'BICYCLE', 'CAR', 'OTHER')),
    start_time      TIME NOT NULL,
    end_time        TIME NOT NULL,
    fee             NUMERIC(12,2) NOT NULL CHECK (fee >= 0),
    card_type       VARCHAR(20) NOT NULL DEFAULT 'CASUAL' CHECK (card_type IN ('MONTHLY', 'CASUAL')),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_by      BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS parking_logs (
    log_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id         BIGINT REFERENCES cards(card_id) ON UPDATE CASCADE ON DELETE SET NULL,
    card_uid        VARCHAR(100) NOT NULL,
    vehicle_id      BIGINT REFERENCES vehicles(vehicle_id) ON UPDATE CASCADE ON DELETE SET NULL,
    parking_lot_id  BIGINT REFERENCES parking_lots(parking_lot_id) ON UPDATE CASCADE ON DELETE SET NULL,
    guard_in_id     BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    guard_out_id    BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    plate_in        VARCHAR(20) NOT NULL,
    plate_out       VARCHAR(20),
    time_in         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    time_out        TIMESTAMPTZ,
    image_face_in   TEXT,
    image_plate_in  TEXT,
    image_face_out  TEXT,
    image_plate_out TEXT,
    fee             NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (fee >= 0),
    status          VARCHAR(20) NOT NULL DEFAULT 'IN_PARKING' CHECK (status IN ('IN_PARKING', 'COMPLETED', 'WARNING')),
    override_reason TEXT,
    CHECK (time_out IS NULL OR time_out >= time_in),
    CHECK ((status = 'IN_PARKING' AND time_out IS NULL) OR status <> 'IN_PARKING')
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id          BIGINT REFERENCES parking_logs(log_id) ON UPDATE CASCADE ON DELETE SET NULL,
    registration_id BIGINT REFERENCES monthly_card_registrations(registration_id) ON UPDATE CASCADE ON DELETE SET NULL,
    amount          NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    payment_method  VARCHAR(20) NOT NULL CHECK (payment_method IN ('CASH', 'BANK_TRANSFER', 'E_WALLET', 'OTHER')),
    payment_status  VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (payment_status IN ('PENDING', 'PAID', 'REFUNDED', 'FAILED')),
    paid_at         TIMESTAMPTZ,
    received_by     BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    transaction_ref VARCHAR(120),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (log_id IS NOT NULL OR registration_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS incidents (
    incident_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id          BIGINT REFERENCES parking_logs(log_id) ON UPDATE CASCADE ON DELETE SET NULL,
    card_id         BIGINT REFERENCES cards(card_id) ON UPDATE CASCADE ON DELETE SET NULL,
    reported_by     BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    resolved_by     BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    incident_type   VARCHAR(30) NOT NULL CHECK (incident_type IN ('PLATE_MISMATCH', 'LOST_CARD', 'LONG_STAY', 'UNKNOWN_VEHICLE', 'OTHER')),
    description     TEXT NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'INVESTIGATING', 'RESOLVED', 'CLOSED')),
    resolution_note TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at     TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS audit_logs (
    audit_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    action          VARCHAR(100) NOT NULL,
    entity_name     VARCHAR(80) NOT NULL,
    entity_id       VARCHAR(80),
    details         JSONB,
    ip_address      INET,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes for common lookups and parking-lot reports.
CREATE INDEX IF NOT EXISTS idx_vehicles_plate_number ON vehicles(plate_number);
CREATE INDEX IF NOT EXISTS idx_cards_status ON cards(status);
CREATE INDEX IF NOT EXISTS idx_cards_user_id ON cards(user_id);
CREATE INDEX IF NOT EXISTS idx_parking_logs_card_uid ON parking_logs(card_uid);
CREATE INDEX IF NOT EXISTS idx_parking_logs_plate_in ON parking_logs(plate_in);
CREATE INDEX IF NOT EXISTS idx_parking_logs_status_time_in ON parking_logs(status, time_in);
CREATE INDEX IF NOT EXISTS idx_parking_logs_time_in ON parking_logs(time_in);
CREATE INDEX IF NOT EXISTS idx_payments_status_paid_at ON payments(payment_status, paid_at);
CREATE INDEX IF NOT EXISTS idx_incidents_status_created_at ON incidents(status, created_at);

-- Helpful view: vehicles currently inside the parking lot.
CREATE OR REPLACE VIEW current_parked_vehicles AS
SELECT pl.log_id, pl.card_uid, pl.plate_in, pl.time_in,
       pl.parking_lot_id, lot.lot_name,
       pl.vehicle_id, pl.guard_in_id
FROM parking_logs pl
LEFT JOIN parking_lots lot ON lot.parking_lot_id = pl.parking_lot_id
WHERE pl.status = 'IN_PARKING' AND pl.time_out IS NULL;
